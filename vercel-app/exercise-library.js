export const FILTER_LEVELS = ["מתחיל","בינוני","מתקדם"];
export function searchExercises({query="", category="", level=""}={}) {
 const normalized = String(query).trim().toLocaleLowerCase("he");
 return EXERCISES.filter(item =>
  (!category || item.category === category) &&
  (!level || item.level === level) &&
  (!normalized || [item.name,item.category,item.equipment].some(text => text.toLocaleLowerCase("he").includes(normalized)))
 );
}

